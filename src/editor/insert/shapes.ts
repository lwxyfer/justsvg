import type { InsertAsset } from './catalog';
function shape(
  id: string,
  label: string,
  category: string,
  body: string,
  keywords = '',
  width = 160,
  height = 96,
): InsertAsset {
  return {
    id: `shape-${id}`,
    label,
    category,
    keywords: `${id} ${keywords} ${category}`,
    svg: `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" fill="#eff6ff" stroke="#3b82f6" stroke-width="2" stroke-linejoin="round" stroke-linecap="round">${body}</svg>`,
    width,
    height,
  };
}
const basic = (id: string, label: string, body: string, keywords = '', size?: number) =>
  shape(id, label, '基础图形', body, keywords, size || 160, size || 96);
const flow = (id: string, label: string, body: string, keywords = '') =>
  shape(id, label, '流程图', body, `flowchart ${keywords}`);
const container = (
  id: string,
  label: string,
  body: string,
  keywords = '',
  width = 240,
  height = 160,
) => shape(id, label, '容器与注释', body, keywords, width, height);
const architecture = (id: string, label: string, body: string, keywords = '') =>
  shape(id, label, '架构符号', body, keywords);
const arrowDef =
  '<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0 0 10 5 0 10Z" fill="#3b82f6" stroke="none"/></marker></defs>';
const connector = (
  id: string,
  label: string,
  body: string,
  arrow = false,
  keywords = '',
  height = 64,
) => shape(id, label, '连接线', (arrow ? arrowDef : '') + body, keywords, 160, height);
const blockArrow = (id: string, label: string, points: string) =>
  shape(id, label, '块状箭头', `<polygon points="${points}"/>`, 'block arrow 方向');
function polygonPoints(sides: number, inner = 1) {
  return Array.from({ length: sides }, (_, i) => {
    const angle = (i * Math.PI * 2) / sides - Math.PI / 2,
      r = i % 2 ? 44 * inner : 44;
    return `${(48 + Math.cos(angle) * r).toFixed(2)},${(48 + Math.sin(angle) * r).toFixed(2)}`;
  }).join(' ');
}
