export function describeIcon(name) {
  const tokens = name
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1 $2')
    .split(' ');
  const translated = tokens.map((t) => words[t.toLowerCase()] || t);
  const category = rules.find(([, pattern]) => pattern.test(name))?.[0] || '其他图标';
  return {
    label: translated.join(' '),
    category,
    keywords: `${tokens.join(' ')} ${translated.join(' ')} ${category}`,
  };
}
